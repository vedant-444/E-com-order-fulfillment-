"""
Data Profiling Framework
Profiles datasets for row counts, null values, distinct values, duplicate analysis, and foreign key anomalies
"""

import csv
import json
from collections import Counter
from pathlib import Path

class DataProfiler:
    def __init__(self):
        self.profile_results = {}

    def profile_file(self, file_path: Path, primary_key: str = None) -> dict:
        """Profiles a single CSV file."""
        if not file_path.exists():
            return {"error": f"File {file_path} not found"}

        total_rows = 0
        column_nulls = Counter()
        column_distinct = {}
        exact_row_hashes = set()
        duplicate_rows = 0
        pk_counter = Counter()
        headers = []

        with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
            reader = csv.DictReader(f)
            headers = reader.fieldnames or []
            for h in headers:
                column_distinct[h] = set()

            for row in reader:
                total_rows += 1
                row_str = "|".join(str(row.get(h, "")) for h in headers)
                if row_str in exact_row_hashes:
                    duplicate_rows += 1
                else:
                    exact_row_hashes.add(row_str)

                for h in headers:
                    val = row.get(h)
                    if val is None or str(val).strip() in {"", "null", "None"}:
                        column_nulls[h] += 1
                    else:
                        if len(column_distinct[h]) < 1000:
                            column_distinct[h].add(str(val).strip())

                if primary_key and primary_key in row:
                    pk_val = str(row[primary_key]).strip()
                    if pk_val:
                        pk_counter[pk_val] += 1

        pk_duplicates = sum(1 for k, count in pk_counter.items() if count > 1)

        profile = {
            "file_name": file_path.name,
            "total_records": total_rows,
            "duplicate_exact_rows": duplicate_rows,
            "primary_key": primary_key,
            "pk_duplicate_keys": pk_duplicates,
            "column_metrics": {
                h: {
                    "null_count": column_nulls[h],
                    "null_percentage": round((column_nulls[h] / total_rows * 100), 2) if total_rows > 0 else 0,
                    "distinct_sample_count": len(column_distinct[h])
                }
                for h in headers
            }
        }
        self.profile_results[file_path.name] = profile
        return profile

    def generate_markdown_report(self) -> str:
        """Generates a GitHub-flavored Markdown profiling report."""
        md = ["# Data Profiling & Quality Assessment Report\n",
              "Generated by OrderFlow360 Automated Profiler\n"]
        
        for fname, prof in self.profile_results.items():
            md.append(f"## Dataset: `{fname}`")
            md.append(f"- **Total Records**: {prof['total_records']:,}")
            md.append(f"- **Exact Duplicate Rows**: {prof['duplicate_exact_rows']:,}")
            if prof.get("primary_key"):
                md.append(f"- **Key Duplicate Records ({prof['primary_key']})**: {prof['pk_duplicate_keys']:,}")
            
            md.append("\n| Column Name | Null Count | Null % | Distinct Sample Count |")
            md.append("|---|---|---|---|")
            for col, met in prof["column_metrics"].items():
                md.append(f"| `{col}` | {met['null_count']:,} | {met['null_percentage']}% | {met['distinct_sample_count']:,} |")
            md.append("\n---\n")

        return "\n".join(md)
