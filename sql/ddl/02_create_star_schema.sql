-- Star Schema Dimensional Model DDL
-- Dimensions: DIM_CUSTOMER (SCD Type 2), DIM_COURIER, DIM_PRODUCT, DIM_DATE
-- Fact: FACT_ORDER_FULFILLMENT

DROP TABLE IF EXISTS FACT_ORDER_FULFILLMENT;
DROP TABLE IF EXISTS DIM_CUSTOMER;
DROP TABLE IF EXISTS DIM_COURIER;
DROP TABLE IF EXISTS DIM_PRODUCT;
DROP TABLE IF EXISTS DIM_DATE;

-- Customer Dimension with SCD Type 2 History Tracking
CREATE TABLE DIM_CUSTOMER (
    CUSTOMER_KEY INTEGER PRIMARY KEY AUTOINCREMENT,
    CUSTOMER_ID VARCHAR(50) NOT NULL,
    CUSTOMER_NAME VARCHAR(100),
    EMAIL VARCHAR(150),
    PHONE VARCHAR(50),
    CITY VARCHAR(100),
    STATE VARCHAR(100),
    PINCODE VARCHAR(20),
    CUSTOMER_SEGMENT VARCHAR(50),
    START_DATE TIMESTAMP NOT NULL,
    END_DATE TIMESTAMP,
    IS_CURRENT INTEGER DEFAULT 1,
    VERSION INTEGER DEFAULT 1,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_dim_cust_id ON DIM_CUSTOMER(CUSTOMER_ID);
CREATE INDEX idx_dim_cust_current ON DIM_CUSTOMER(CUSTOMER_ID, IS_CURRENT);

-- Courier Dimension
CREATE TABLE DIM_COURIER (
    COURIER_KEY INTEGER PRIMARY KEY AUTOINCREMENT,
    COURIER_ID VARCHAR(20) NOT NULL UNIQUE,
    COURIER_NAME VARCHAR(100) NOT NULL,
    SLA_DAYS INTEGER NOT NULL,
    SERVICE_TYPE VARCHAR(50),
    REGION_COVERAGE VARCHAR(50),
    ACTIVE_FLAG VARCHAR(5) DEFAULT 'Y'
);

CREATE INDEX idx_dim_courier_name ON DIM_COURIER(COURIER_NAME);

-- Product Dimension
CREATE TABLE DIM_PRODUCT (
    PRODUCT_KEY INTEGER PRIMARY KEY AUTOINCREMENT,
    PRODUCT_ID VARCHAR(50) NOT NULL UNIQUE,
    PRODUCT_NAME VARCHAR(150) NOT NULL,
    CATEGORY VARCHAR(100),
    BASE_UNIT_PRICE REAL
);

CREATE INDEX idx_dim_prod_id ON DIM_PRODUCT(PRODUCT_ID);

-- Date Dimension
CREATE TABLE DIM_DATE (
    DATE_KEY INTEGER PRIMARY KEY, -- e.g. 20260518
    FULL_DATE DATE NOT NULL UNIQUE,
    DAY INTEGER NOT NULL,
    MONTH INTEGER NOT NULL,
    MONTH_NAME VARCHAR(20) NOT NULL,
    QUARTER INTEGER NOT NULL,
    YEAR INTEGER NOT NULL,
    DAY_OF_WEEK VARCHAR(20) NOT NULL,
    IS_WEEKEND INTEGER NOT NULL
);

CREATE INDEX idx_dim_date_full ON DIM_DATE(FULL_DATE);

-- Fact Table: FACT_ORDER_FULFILLMENT
CREATE TABLE FACT_ORDER_FULFILLMENT (
    ORDER_ID VARCHAR(50) PRIMARY KEY,
    CUSTOMER_KEY INTEGER REFERENCES DIM_CUSTOMER(CUSTOMER_KEY),
    COURIER_KEY INTEGER REFERENCES DIM_COURIER(COURIER_KEY),
    PRODUCT_KEY INTEGER REFERENCES DIM_PRODUCT(PRODUCT_KEY),
    ORDER_DATE_KEY INTEGER REFERENCES DIM_DATE(DATE_KEY),
    SHIPPED_DATE_KEY INTEGER REFERENCES DIM_DATE(DATE_KEY),
    DELIVERY_DATE_KEY INTEGER REFERENCES DIM_DATE(DATE_KEY),
    
    ORDER_DATE DATE,
    SHIPPED_DATE DATE,
    DELIVERY_DATE DATE,
    ORDER_STATUS VARCHAR(50) NOT NULL,
    PAYMENT_MODE VARCHAR(50),
    
    -- Measures
    QUANTITY INTEGER NOT NULL,
    UNIT_PRICE REAL NOT NULL,
    TOTAL_AMOUNT REAL NOT NULL,
    DELIVERY_DAYS INTEGER,
    DELAY_DAYS INTEGER,
    SLA_DAYS INTEGER,
    
    -- Business & SLA Flags
    DELIVERED_FLAG INTEGER DEFAULT 0,
    ON_TIME_FLAG INTEGER DEFAULT 0,
    LATE_DELIVERY_FLAG INTEGER DEFAULT 0,
    CANCELLED_FLAG INTEGER DEFAULT 0,
    RETURNED_FLAG INTEGER DEFAULT 0,
    IN_TRANSIT_FLAG INTEGER DEFAULT 0,
    INACTIVE_COURIER_FLAG INTEGER DEFAULT 0,
    
    LAST_UPDATED_TS TIMESTAMP,
    LOADED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_fact_cust ON FACT_ORDER_FULFILLMENT(CUSTOMER_KEY);
CREATE INDEX idx_fact_courier ON FACT_ORDER_FULFILLMENT(COURIER_KEY);
CREATE INDEX idx_fact_status ON FACT_ORDER_FULFILLMENT(ORDER_STATUS);
CREATE INDEX idx_fact_order_date ON FACT_ORDER_FULFILLMENT(ORDER_DATE_KEY);
