-- Staging Tables DDL
-- Raw Ingestion Landing for OrderFlow360 Analytics

DROP TABLE IF EXISTS STG_CUSTOMER_MASTER;
CREATE TABLE STG_CUSTOMER_MASTER (
    CUSTOMER_ID VARCHAR(50),
    CUSTOMER_NAME VARCHAR(100),
    EMAIL VARCHAR(150),
    PHONE VARCHAR(50),
    CITY VARCHAR(100),
    STATE VARCHAR(100),
    PINCODE VARCHAR(20),
    CUSTOMER_SEGMENT VARCHAR(50),
    REGISTRATION_DATE VARCHAR(50),
    LAST_UPDATED_TS VARCHAR(50),
    SOURCE_FILE VARCHAR(100),
    INGESTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

DROP TABLE IF EXISTS STG_ORDER_TRANSACTIONS;
CREATE TABLE STG_ORDER_TRANSACTIONS (
    ORDER_ID VARCHAR(50),
    CUSTOMER_ID VARCHAR(50),
    PRODUCT_ID VARCHAR(50),
    PRODUCT_NAME VARCHAR(150),
    CATEGORY VARCHAR(100),
    UNIT_PRICE VARCHAR(50),
    QUANTITY VARCHAR(50),
    ORDER_DATE VARCHAR(50),
    SHIPPED_DATE VARCHAR(50),
    DELIVERY_DATE VARCHAR(50),
    COURIER_NAME VARCHAR(100),
    ORDER_STATUS VARCHAR(50),
    PAYMENT_MODE VARCHAR(50),
    LAST_UPDATED_TS VARCHAR(50),
    SOURCE_FILE VARCHAR(100),
    INGESTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

DROP TABLE IF EXISTS STG_COURIER_SLA;
CREATE TABLE STG_COURIER_SLA (
    COURIER_ID VARCHAR(20),
    COURIER_NAME VARCHAR(100),
    SLA_DAYS INTEGER,
    SERVICE_TYPE VARCHAR(50),
    REGION_COVERAGE VARCHAR(50),
    ACTIVE_FLAG VARCHAR(5),
    INGESTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
