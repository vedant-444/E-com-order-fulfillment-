-- Data Quality Audit & Reconciliation DDL

DROP TABLE IF EXISTS DQ_AUDIT_LOG;
CREATE TABLE DQ_AUDIT_LOG (
    LOG_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    FILE_NAME VARCHAR(100),
    RECORD_KEY VARCHAR(100),
    RULE_NAME VARCHAR(100) NOT NULL,
    SEVERITY VARCHAR(20) NOT NULL, -- REJECT, QUARANTINE, WARNING, TRANSFORM
    ACTION_TAKEN VARCHAR(100) NOT NULL,
    ERROR_MESSAGE TEXT,
    RAW_PAYLOAD TEXT,
    LOG_TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_dq_rule ON DQ_AUDIT_LOG(RULE_NAME);
CREATE INDEX idx_dq_severity ON DQ_AUDIT_LOG(SEVERITY);
CREATE INDEX idx_dq_file ON DQ_AUDIT_LOG(FILE_NAME);

DROP TABLE IF EXISTS RECONCILIATION_AUDIT;
CREATE TABLE RECONCILIATION_AUDIT (
    AUDIT_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    METRIC_NAME VARCHAR(100) NOT NULL,
    SOURCE_COUNT INTEGER NOT NULL,
    TARGET_COUNT INTEGER NOT NULL,
    VARIANCE INTEGER NOT NULL,
    MATCH_STATUS VARCHAR(20) NOT NULL, -- MATCH, VARIANCE
    NOTES TEXT,
    AUDITED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

DROP TABLE IF EXISTS KPI_DAILY_SNAPSHOT;
CREATE TABLE KPI_DAILY_SNAPSHOT (
    SNAPSHOT_DATE DATE PRIMARY KEY,
    TOTAL_ORDERS INTEGER,
    DELIVERED_ORDERS INTEGER,
    CANCELLED_ORDERS INTEGER,
    RETURNED_ORDERS INTEGER,
    IN_TRANSIT_ORDERS INTEGER,
    AVG_DELIVERY_DAYS REAL,
    AVG_SLA_DAYS REAL,
    ON_TIME_DELIVERY_PCT REAL,
    LATE_DELIVERY_PCT REAL,
    SHIPMENT_SUCCESS_RATE_PCT REAL,
    TOTAL_REVENUE REAL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
