-- Query 03: Top 10 Customers by Order Volume and Total Spend
-- Leverages DIM_CUSTOMER SCD Type 2 dimension linkage

SELECT 
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    c.CITY,
    c.STATE,
    c.CUSTOMER_SEGMENT,
    COUNT(f.ORDER_ID) AS TOTAL_ORDERS,
    SUM(f.DELIVERED_FLAG) AS DELIVERED_ORDERS,
    ROUND(SUM(f.TOTAL_AMOUNT), 2) AS TOTAL_SPEND,
    ROUND(AVG(f.TOTAL_AMOUNT), 2) AS AVG_ORDER_VALUE
FROM FACT_ORDER_FULFILLMENT f
JOIN DIM_CUSTOMER c ON f.CUSTOMER_KEY = c.CUSTOMER_KEY
GROUP BY c.CUSTOMER_ID, c.CUSTOMER_NAME, c.CITY, c.STATE, c.CUSTOMER_SEGMENT
ORDER BY TOTAL_ORDERS DESC, TOTAL_SPEND DESC
LIMIT 10;
