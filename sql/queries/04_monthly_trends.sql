-- Query 04: Monthly Fulfillment Trends & Revenue Evolution
-- Aggregates orders, delivery performance, and revenue by month

SELECT
    d.YEAR,
    d.MONTH,
    d.MONTH_NAME,
    COUNT(f.ORDER_ID) AS MONTHLY_ORDERS,
    SUM(f.DELIVERED_FLAG) AS DELIVERED_ORDERS,
    SUM(f.CANCELLED_FLAG) AS CANCELLED_ORDERS,
    SUM(f.RETURNED_FLAG) AS RETURNED_ORDERS,
    ROUND(AVG(CASE WHEN f.DELIVERED_FLAG = 1 THEN f.DELIVERY_DAYS END), 2) AS AVG_DELIVERY_DAYS,
    ROUND(SUM(f.TOTAL_AMOUNT), 2) AS MONTHLY_REVENUE
FROM FACT_ORDER_FULFILLMENT f
JOIN DIM_DATE d ON f.ORDER_DATE_KEY = d.DATE_KEY
GROUP BY d.YEAR, d.MONTH, d.MONTH_NAME
ORDER BY d.YEAR ASC, d.MONTH ASC;
